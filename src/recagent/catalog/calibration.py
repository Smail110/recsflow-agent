"""Константы калибровки синтетического каталога.

Числа получены из открытых данных, а не придуманы, и пересчитываются скриптом::

    python -m scripts.calibrate_catalog

Скрипт читает ``data/raw/u.item`` и ``data/raw/u.data``, печатает сверку каждого
числа с заявленным здесь и сохраняет JSON со всеми промежуточными величинами.
Тест ``tests/unit/test_calibration.py`` превращает ту же сверку в регрессионную
проверку: если кто-то поправит константу на глаз, CI это увидит (при наличии
исходников; без них тест пропускается, потому что исходные данные не коммитятся).

Источники:
  * MovieLens-100k (apache-2.0), зеркало на HuggingFace ``includeno/movielens-100k``:
    ``u.data`` — 100 000 оценок, ``u.item`` — 1 682 объекта. Отсюда частоты жанров,
    распределение оценок, длинный хвост популярности и форма распределения качества.

Что калибруем и что остаётся допущением:
  * частоты жанров — перенесены из MovieLens, но сопоставлены нашим семи жанрам
    (драма <- Drama, комедия <- Comedy, детектив <- Mystery U Crime, фантастика <- Sci-Fi,
    приключения <- Adventure). Это перенос долей, а не точное соответствие.
    Для «детектива» берётся ОБЪЕДИНЕНИЕ Mystery и Crime, а не сумма долей: объект
    может иметь оба флага, и сумма его посчитала бы дважды (0.1011 против 0.0951).
  * популярность — эмпирические квантили числа оценок на объект.
  * качество — наблюдаемые средние рейтинги; шкала 1..5 нормирована в 0..1.
  * длительности, число сезонов, тон и годы — ДОПУЩЕНИЯ, в MovieLens их нет.
    Форма распределений (длинный хвост, перекос к свежим релизам) взята из того же
    набора, конкретные границы — наши.

Реальные названия фильмов и сериалов в каталог не попадают: названия процедурные
(см. generator.py). Из MovieLens берутся только распределения.
"""

